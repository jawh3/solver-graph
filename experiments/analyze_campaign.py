#!/usr/bin/env python3
"""
experiments/analyze_campaign.py — analyze the causal-credit campaign.

Produces the solution paper's headline numbers in one command:
  1. Held-out solve rate per condition (B0 / B2 / outcome / observational / causal),
     compute disclosed (train_solves + causal_rerolls).
  2. PAIRED comparisons on the common held-out (challenge, seed) items: the eval set
     and seeds are identical across conditions, so observational-vs-outcome,
     observational-vs-B2, causal-vs-outcome are within-item paired (bootstrap CI +
     exact McNemar) — the significance the headline needs.
  3. The OUTCOME bandit's learned Q by ground-truth label (the fooled signal:
     helpful ~ poison).
  4. The OBSERVATIONAL causal ATE computed from the SAME outcome-condition logs
     (the cheap fix: separates helpful / distractor / poison) — zero extra inference.
  5. The ACTIVE causal bandit's learned Q by label (re-rolls; assumption-light check).
  6. Emits paper/numbers_solution.tex (\providecommand-safe) so the paper recompiles
     against real campaign numbers with one command.

Reads results/campaign/{summary.json, progress.json, logs/campaign_<cond>/, state/<cond>/}.
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

from instrumentation.jsonl_logger import load_runs
from ope.causal_value import observational_lesson_values, summarize_by_label
from evaluation.stats import paired_bootstrap_ci, mcnemar_exact
from retrieval.embedder import MockEmbedder
import benchmark.hard_ctf as hard


def _truth(families=None):
    # families: list of family names actually used by the campaign (from summary.json) so
    # the ground-truth node IDs match a SCALED grid run; None -> original core families.
    _, truth = hard.build_seed_graph(MockEmbedder(dim=8, seed=1), families=families)
    return truth


def _q_values_by_label(state_dir: Path, truth) -> dict:
    """{label: [per-node MEAN learned Q across the contexts it appears in]}.

    Mean (not max) is the representative per-lesson value a write-back gate would see;
    max-across-contexts would over-promote on a single noisy positive cell.
    """
    bpath = state_dir / "bandit.json"
    if not bpath.exists():
        return {}
    cells = json.loads(bpath.read_text()).get("cells", {})
    per_node = defaultdict(list)
    lab_of = {}
    for ctx, nodes in cells.items():
        for nid, cell in nodes.items():
            if nid in truth and cell["n"] > 0:
                per_node[nid].append(cell["Q"]); lab_of[nid] = truth[nid][0]
    out = defaultdict(list)
    for nid, qs in per_node.items():
        out[lab_of[nid]].append(float(np.mean(qs)))
    return dict(out)


def _q_by_label(state_dir: Path, truth) -> dict:
    vals = _q_values_by_label(state_dir, truth)
    return {lab: {"mean_Q": float(np.mean(xs)), "n": len(xs)} for lab, xs in vals.items()}


def _promotion_from_values(label_values: dict, theta: float = 0.0) -> dict:
    """Fraction of each label's lessons with per-lesson value > theta (a promote-if-
    positive write-back gate). label_values = {label: [per-node value]}."""
    return {lab: {"promote_rate": float(np.mean([v > theta for v in xs])), "n": len(xs)}
            for lab, xs in label_values.items() if xs}


def _ate_values_by_label(vals: dict) -> dict:
    """{label: [per-node ATE]} from observational_lesson_values() output."""
    out = defaultdict(list)
    for nid, d in vals.items():
        if d.get("ate") is not None and d.get("label"):
            out[d["label"]].append(d["ate"])
    return dict(out)


def _eval_vec(cond_prog) -> dict:
    """(name, seed) -> solved for a condition's held-out eval items."""
    vec = {}
    for m in cond_prog.get("metrics", []):
        if m.get("phase") == "eval":
            vec[(m["name"], m["seed"])] = int(m["solved"])
    return vec


def _paired(va: dict, vb: dict):
    """Paired comparison on the common (name,seed) keys. Returns dict or None."""
    keys = sorted(set(va) & set(vb))
    if not keys:
        return None
    a = [va[k] for k in keys]
    b = [vb[k] for k in keys]
    pr = paired_bootstrap_ci(a, b, n_boot=10000, seed=0)
    mc = mcnemar_exact(a, b)
    return {"n": len(keys), "mean_a": float(np.mean(a)), "mean_b": float(np.mean(b)),
            "diff": pr.mean_diff, "ci_lo": pr.ci_low, "ci_hi": pr.ci_high,
            "boot_p": pr.p_value_sign, "mcnemar_p": mc["p_value"],
            "b01": mc["b01"], "b10": mc["b10"], "significant": pr.significant}


def _fmt_pct(x):
    return f"{100*x:.1f}\\%" if x is not None else "--"


def _emit_macros(out, path: Path):
    """Write \\providecommand-safe LaTeX macros for the solution paper."""
    lines = ["% Auto-generated by experiments/analyze_campaign.py — do not edit by hand.",
             "% Solution-paper numbers (real campaign). Each traces to results/campaign/.",
             ""]

    def mac(name, val):
        lines.append(f"\\providecommand{{\\{name}}}{{}}\\renewcommand{{\\{name}}}{{{val}}}")

    sr = out.get("solve_rates", {})
    mac("CampBzero", _fmt_pct(sr.get("B0")))
    mac("CampBtwo", _fmt_pct(sr.get("B2")))
    mac("CampOutcome", _fmt_pct(sr.get("outcome")))
    mac("CampObs", _fmt_pct(sr.get("observational")))
    mac("CampCausal", _fmt_pct(sr.get("causal")))

    meta = out.get("meta", {})
    mac("CampNheldout", str(meta.get("n_eval_heldout", "--")))
    mac("CampNtrain", str(meta.get("n_train", "--")))
    mac("CampEpochs", str(meta.get("epochs", "--")))
    mac("CampEvalSeeds", str(meta.get("eval_seeds", "--")))
    mac("CampRerolls", str(out.get("compute", {}).get("causal_rerolls", "--")))

    # paired comparisons: macro prefix -> result
    pc = out.get("paired", {})

    def pair_macros(prefix, key):
        r = pc.get(key)
        if not r:
            mac(prefix, "--"); mac(prefix + "CI", "--"); mac(prefix + "P", "--")
            return
        mac(prefix, f"{100*r['diff']:+.1f}\\,pp")
        mac(prefix + "CI", f"[{100*r['ci_lo']:+.1f}, {100*r['ci_hi']:+.1f}]")
        # report the smaller of bootstrap / McNemar as the headline p (both shown in json)
        mac(prefix + "P", f"{r['mcnemar_p']:.3f}")
        mac(prefix + "N", str(r["n"]))

    pair_macros("ObsVsOutcome", "obs_vs_outcome")
    pair_macros("ObsVsBtwo", "obs_vs_B2")
    pair_macros("ObsVsBzero", "obs_vs_B0")
    pair_macros("CausalVsOutcome", "causal_vs_outcome")
    pair_macros("BtwoVsBzero", "B2_vs_B0")

    # learned Q (outcome = fooled, causal = active check)
    lq = out.get("learned_Q", {})
    for cond, pre in (("outcome", "Out"), ("causal", "Act")):
        q = lq.get(cond, {})
        for lab, suff in (("helpful", "True"), ("poison", "Poison"), ("distractor", "Distract")):
            if lab in q:
                mac(f"{pre}Q{suff}", f"{q[lab]['mean_Q']:+.3f}")
        if "helpful" in q and "poison" in q:
            mac(f"{pre}QGap", f"{q['helpful']['mean_Q']-q['poison']['mean_Q']:+.3f}")

    # observational ATE on the SAME outcome logs (the separation)
    obs = out.get("observational", {}).get("outcome", {})
    for lab, suff in (("helpful", "True"), ("poison", "Poison"), ("distractor", "Distract")):
        if lab in obs:
            mac(f"ObsAte{suff}", f"{obs[lab]['mean_ate']:+.3f}")
    if "helpful" in obs and "poison" in obs:
        mac("ObsAteGap", f"{obs['helpful']['mean_ate']-obs['poison']['mean_ate']:+.3f}")

    # propagation: poison/helpful promotion under a promote-if-positive write-back gate.
    # Out = outcome credit's own Q; Obs = the observational causal value (per-node IPW
    # ATE) on the SAME outcome logs (apples-to-apples, only the credit signal differs).
    promo = out.get("promotion", {})
    for src, pre in (("outcome", "Out"), ("causal_ate_outcome", "Obs")):
        pr = promo.get(src, {})
        for lab, suff in (("helpful", "Help"), ("poison", "Poison")):
            if lab in pr:
                mac(f"Promote{suff}{pre}", f"{100*pr[lab]['promote_rate']:.0f}\\%")

    path.write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="results/campaign")
    ap.add_argument("--emit", default="paper/numbers_solution.tex")
    args = ap.parse_args()
    root = Path(args.dir)
    summ = json.loads((root / "summary.json").read_text()) if (root / "summary.json").exists() else {"conditions": {}}
    prog = json.loads((root / "progress.json").read_text()) if (root / "progress.json").exists() else {"conditions": {}}
    truth = _truth(summ.get("families"))

    out = {"solve_rates": {}, "paired": {}, "learned_Q": {}, "observational": {},
           "compute": {}, "meta": {}}

    # ---- solve rates per condition (from progress eval metrics) ----
    eval_vecs = {}
    print("=" * 72)
    print("HELD-OUT SOLVE RATE (compute disclosed):")
    print(f"  {'condition':14s}{'heldout':>9s}{'n':>6s}{'train':>8s}{'rerolls':>9s}")
    for name, cp in prog.get("conditions", {}).items():
        vec = _eval_vec(cp)
        eval_vecs[name] = vec
        sr = float(np.mean(list(vec.values()))) if vec else None
        out["solve_rates"][name] = sr
        if name == "causal":
            out["compute"]["causal_rerolls"] = cp.get("causal_rerolls", 0)
        print(f"  {name:14s}{(f'{sr:.3f}' if sr is not None else '-'):>9s}{len(vec):>6d}"
              f"{cp.get('train_solves',0):>8d}{cp.get('causal_rerolls',0):>9d}")

    # ---- paired comparisons on common held-out items ----
    comps = [("obs_vs_outcome", "observational", "outcome"),
             ("obs_vs_B2", "observational", "B2"),
             ("obs_vs_B0", "observational", "B0"),
             ("causal_vs_outcome", "causal", "outcome"),
             ("B2_vs_B0", "B2", "B0")]
    print("\nPAIRED held-out comparisons (within (challenge,seed); + = first wins):")
    for key, a, b in comps:
        if a in eval_vecs and b in eval_vecs:
            r = _paired(eval_vecs[a], eval_vecs[b])
            if r:
                out["paired"][key] = r
                star = "*" if r["significant"] else " "
                print(f"  {a:13s} vs {b:11s} Δ={100*r['diff']:+5.1f}pp "
                      f"CI[{100*r['ci_lo']:+.1f},{100*r['ci_hi']:+.1f}] "
                      f"McNemar p={r['mcnemar_p']:.3f}{star} (n={r['n']}, b01={r['b01']:.0f}/b10={r['b10']:.0f})")

    # ---- learned Q by label (outcome fooled; causal active check) + promotion rate ----
    out["promotion"] = {}
    for cond in ("outcome", "causal", "observational", "outcome_allM"):
        sdir = root / "state" / cond
        q = _q_by_label(sdir, truth)
        if q:
            out["learned_Q"][cond] = q
            print(f"\nLEARNED Q by label [{cond}]:")
            for lab in ("helpful", "poison", "distractor"):
                if lab in q:
                    print(f"  {lab:10s} meanQ={q[lab]['mean_Q']:+.3f} (n={q[lab]['n']})")
            # outcome credit's own value drives a Q>0 write-back gate; the causal
            # signals' promotion is computed below from the per-node ATE (their value).
            if cond in ("outcome", "outcome_allM"):
                promo = _promotion_from_values(_q_values_by_label(sdir, truth), theta=0.0)
                if promo:
                    out["promotion"][cond] = promo
                    print(f"  PROPAGATION (promote-if-Q>0): "
                          + "  ".join(f"{lab}={100*promo[lab]['promote_rate']:.0f}%"
                                      for lab in ("helpful", "poison", "distractor") if lab in promo))

    # ---- OBSERVATIONAL ATE from logs (cheap separation on same data) + ATE-based promotion ----
    for cond in ("outcome", "observational", "causal"):
        runs = load_runs(f"campaign_{cond}", root=str(root / "logs"))
        if not runs:
            continue
        vals = observational_lesson_values(runs, truth=truth)
        sl = summarize_by_label(vals)
        out["observational"][cond] = sl
        print(f"\nOBSERVATIONAL causal ATE from [{cond}] logs (IPW, no re-rolls):")
        for lab in ("helpful", "distractor", "poison"):
            if lab in sl:
                print(f"  {lab:10s} meanATE={sl[lab]['mean_ate']:+.3f} (n={sl[lab]['n']})")
        # The causal credit's promotion: per-node ATE > 0. Headline uses the OUTCOME
        # logs (identical data to the outcome bandit — controls for everything but
        # the credit signal); also report it on the observational condition's own logs.
        promo = _promotion_from_values(_ate_values_by_label(vals), theta=0.0)
        if promo:
            out["promotion"][f"causal_ate_{cond}"] = promo
            print(f"  PROPAGATION (promote-if-ATE>0): "
                  + "  ".join(f"{lab}={100*promo[lab]['promote_rate']:.0f}%"
                              for lab in ("helpful", "poison", "distractor") if lab in promo))

    # ---- meta (from progress, robust to summary.json not existing mid-run) ----
    all_eval = [m for cp in prog.get("conditions", {}).values()
                for m in cp.get("metrics", []) if m.get("phase") == "eval"]
    all_train = [m for cp in prog.get("conditions", {}).values()
                 for m in cp.get("metrics", []) if m.get("phase") == "train"]
    epochs = max([m.get("epoch", 0) for m in all_train], default=-1) + 1
    out["meta"] = {
        "n_eval_heldout": len({m["name"] for m in all_eval}) or summ.get("n_eval_heldout"),
        "n_train": len({m["name"] for m in all_train}) or summ.get("n_train"),
        "eval_seeds": len({m["seed"] for m in all_eval}) or summ.get("eval_seeds"),
        "epochs": epochs if epochs > 0 else summ.get("epochs"),
    }

    (root / "analysis.json").write_text(json.dumps(out, indent=2, default=str))
    print(f"\nwrote {root/'analysis.json'}")

    emit_path = Path(args.emit)
    if emit_path.parent.exists():
        _emit_macros(out, emit_path)
        print(f"wrote {emit_path}")


if __name__ == "__main__":
    main()
